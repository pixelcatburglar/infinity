//! Strict-prefix replay of the canonical journal into durable index rows.
//! No client module is mirrored; rows live in `game.sov_development*` and the
//! original journal is replayed through `dao::progress::sovereignty`. A late
//! source re-folds the affected suffix from the newest usable checkpoint, so a
//! receipt is acknowledged only after the complete suffix through EOF.
//! Checkpoints record a baseline only where a folded source actually crosses a
//! decay-interval or activation boundary; empty offline spans stay row-free.

use std::sync::Arc;
use crate::db::Transaction;
use crate::{dao::{lua_content::activations, progress::sovereignty::{self as replay_dao, FactOrder}, sovereignty::development::{self, CheckpointRow, DevelopmentRow}}, db::{executor::Executor, outbox::Outbox}, lua::content::indices::NAMESPACE, progress::ApplyError, services::{db_err, CallError}};
use super::{activation::PolicyHistory, model::{DevelopmentPublication, PointState, SourceSlice}, progress::CONSUMER_KEY, rules};

/// Server replay policy: slices are folded in pages so a busy system's history
/// never lands in memory at once; acknowledgement still requires end of facts.
const PAGE: i64 = 256;

fn invalid(reason: impl std::fmt::Display) -> CallError {
    db_err(anyhow::anyhow!("invalid development-index state: {reason}"))
}

/// The newest decay-interval or activation boundary strictly after `prev` and
/// not after `at`; the interval grid is FILETIME-aligned per active segment.
/// A boundary equal to `prev` is already folded and never reported.
fn crossed_boundary(history: &PolicyHistory, prev: i64, at: i64) -> Option<i64> {
    if at <= prev {
        return None;
    }
    let mut best: Option<i64> = None;
    let mut consider = |boundary: i64| {
        if boundary > prev && boundary <= at && best.is_none_or(|b| boundary > b) {
            best = Some(boundary);
        }
    };
    for (index, segment) in history.segments.iter().enumerate() {
        consider(segment.starts_at);
        let end = history.segments.get(index + 1).map_or(at, |next| at.min(next.starts_at.saturating_sub(1)));
        if segment.starts_at > end {
            continue;
        }
        let interval = segment.definitions.decay_interval_ticks;
        if interval <= 0 {
            continue;
        }
        // The next segment owns its activation instant; the current end is inclusive.
        let last = end.div_euclid(interval) * interval;
        if last >= segment.starts_at {
            consider(last);
        }
    }
    best
}

/// The next state and the minimal checkpoint suffix generated by a fold.
struct FoldOut {
    next: DevelopmentRow,
    checkpoints: Vec<CheckpointRow>,
}

/// Incremental fold keeps the final interval baseline and strict-prefix
/// checkpoint state across page boundaries.
struct Fold<'a> {
    row: &'a DevelopmentRow,
    history: &'a PolicyHistory,
    now: i64,
    trend_start: i64,
    state: PointState,
    baseline: Option<PointState>,
    prev: Option<i64>,
    tail: Option<FactOrder>,
    checkpoints: Vec<CheckpointRow>,
}

impl<'a> Fold<'a> {
    fn new(row: &'a DevelopmentRow, anchor: PointState, prev: Option<i64>, tail: Option<FactOrder>, history: &'a PolicyHistory, now: i64) -> Result<Self, CallError> {
        let segment = history.segment_at(now).ok_or_else(|| invalid("no active policy segment"))?;
        let interval = segment.definitions.decay_interval_ticks;
        if interval <= 0 { return Err(invalid("invalid decay interval")); }
        let trend_start = now.checked_sub(now.rem_euclid(interval)).ok_or_else(|| invalid("interval alignment"))?.max(segment.starts_at);
        let baseline = if anchor.at > trend_start || (anchor.at == trend_start && prev.is_some_and(|at| at >= trend_start)) {
            Some(PointState { at: row.trend_start_at, military: row.military_trend_base, industrial: row.industrial_trend_base })
        } else { None };
        if baseline.is_some_and(|base| base.at != trend_start) {
            return Err(invalid("stored trend baseline does not match interval"));
        }
        Ok(Self { row, history, now, trend_start, state: anchor, baseline, prev, tail, checkpoints: Vec::new() })
    }

    fn push(&mut self, slice: &SourceSlice) -> Result<(), CallError> {
        let at = slice.order.occurred_at;
        if at > self.now || at < self.state.at || self.tail.as_ref().is_some_and(|tail| slice.order <= *tail) {
            return Err(invalid("source order outside fold"));
        }
        if self.baseline.is_none() && self.state.at <= self.trend_start && at >= self.trend_start {
            self.baseline = Some(rules::advance(self.state, self.trend_start, self.history)?);
        }
        if let Some(previous) = self.prev {
            if let Some(boundary) = crossed_boundary(self.history, previous.max(self.state.at.saturating_sub(1)), at) {
                self.state = rules::advance(self.state, boundary, self.history)?;
                let segment = self.history.segment_at(boundary).ok_or_else(|| invalid("checkpoint without policy"))?;
                self.checkpoints.push(CheckpointRow { system_id: self.row.system_id, checkpoint_at: boundary, military_points: self.state.military, industrial_points: self.state.industrial, activation_ordinal: segment.ordinal });
            }
        }
        self.state = rules::advance(self.state, at, self.history)?;
        let definitions = &self.history.segment_at(at).ok_or_else(|| invalid("no active policy segment"))?.definitions;
        self.state = rules::credit(self.state, slice.increment.clone(), definitions)?;
        self.prev = Some(at);
        self.tail = Some(slice.order.clone());
        Ok(())
    }

    fn finish(mut self) -> Result<FoldOut, CallError> {
        if self.baseline.is_none() && self.state.at <= self.trend_start {
            self.baseline = Some(rules::advance(self.state, self.trend_start, self.history)?);
        }
        self.state = rules::advance(self.state, self.now, self.history)?;
        let base = self.baseline.ok_or_else(|| invalid("missing trend baseline"))?;
        let ordinal = self.history.segment_at(self.now).ok_or_else(|| invalid("no active policy segment"))?.ordinal;
        Ok(FoldOut {
            next: DevelopmentRow {
                system_id: self.row.system_id, military_points: self.state.military, industrial_points: self.state.industrial,
                evaluated_at: self.now, revision: self.row.revision, activation_ordinal: ordinal,
                trend_start_at: base.at, military_trend_base: base.military, industrial_trend_base: base.industrial, tail: self.tail,
            },
            checkpoints: self.checkpoints,
        })
    }
}

/// Read the complete eligible suffix `[from, through]` in fixed pages; the
/// named pending event participates, other pending deliveries never do.
async fn replay_all(ex: &(impl Executor + ?Sized), sde: &crate::sde::Sde, row: &DevelopmentRow, history: &PolicyHistory, anchor: PointState, include_pending: Option<&str>, from: i64, through: i64) -> Result<FoldOut, CallError> {
    let mut after: Option<FactOrder> = None;
    let prefix_tail = row.tail.clone().filter(|tail| tail.occurred_at < from);
    let mut fold = Fold::new(row, anchor, None, prefix_tail, history, through)?;
    loop {
        let page = replay_dao::replay_page(ex, CONSUMER_KEY, row.system_id, include_pending, from, through, after.as_ref(), PAGE).await?;
        if page.is_empty() { break; }
        let mut ids: Vec<_> = page.iter().map(|slice| slice.event_id.clone()).collect();
        ids.sort_unstable();
        ids.dedup();
        let envelopes = crate::dao::progress::envelopes(ex, &ids).await?;
        let mut facts = std::collections::HashMap::with_capacity(envelopes.len());
        for envelope in envelopes {
            let fact = super::source::map(&envelope, sde)?.ok_or_else(|| invalid("excluded event in replay"))?;
            if fact.system_id != row.system_id || facts.insert(envelope.event_id, fact).is_some() {
                return Err(invalid("replay envelope system or identity mismatch"));
            }
        }
        for slice in &page {
            let valid = facts.get(&slice.event_id).is_some_and(|fact| fact.slices
                .binary_search_by(|source| source.order.cmp(&slice.order))
                .is_ok_and(|index| fact.slices[index].increment == slice.increment));
            if !valid { return Err(invalid("replay slice does not match original envelope")); }
        }
        after = Some(page.last().expect("non-empty page").order.clone());
        for slice in page {
            fold.push(&SourceSlice { order: slice.order, increment: slice.increment })?;
        }
    }
    let result = fold.finish()?;
    if row.tail.as_ref().is_some_and(|old| old.occurred_at >= from && result.next.tail.as_ref().is_none_or(|tail| tail < old)) {
        return Err(invalid("replay omitted previously folded tail"));
    }
    Ok(result)
}

/// The prepared write set of one delivery or refresh: the retained handle and
/// captured namespace head for the stability check, the guarded row, the
/// checkpoint suffix and the actor publication.
pub(crate) struct PreparedRefresh {
    system: i64,
    previous: DevelopmentRow,
    next: DevelopmentRow,
    checkpoints: Vec<CheckpointRow>,
    replace_from: Option<i64>,
    head_ordinal: Option<i64>,
    retained: crate::lua::RetainedPolicies,
    policies: Arc<PolicyHistory>,
}

impl PreparedRefresh {
    /// Whether the semantic state changed; `evaluated_at` anchoring alone is
    /// analytically identical and does not count.
    pub(crate) fn changed(&self) -> bool {
        let (old, next) = (&self.previous, &self.next);
        next.military_points != old.military_points || next.industrial_points != old.industrial_points
            || next.trend_start_at != old.trend_start_at || next.military_trend_base != old.military_trend_base
            || next.industrial_trend_base != old.industrial_trend_base || next.tail != old.tail
            || next.activation_ordinal != old.activation_ordinal || self.replace_from.is_some()
    }

    /// Shared namespace fence, the non-blocking namespace-version stability
    /// check and the state row lock with its expected revision. Reads only; no
    /// write, outbox, Lua or World may run while these locks are held.
    pub(crate) async fn prelock(&self, tx: &Transaction<'_>) -> Result<(), ApplyError> {
        activations::lock_namespace(tx, NAMESPACE, false).await?;
        if !self.retained.is_current(NAMESPACE, self.head_ordinal)? {
            return Err(ApplyError::Reprepare);
        }
        match development::lock(tx, self.system).await? {
            Some(row) if row == self.previous => Ok(()),
            _ => Err(ApplyError::Reprepare),
        }
    }

    fn expected_revision(&self) -> i64 { self.previous.revision }

    /// Guarded state write plus checkpoint-suffix replace. A stale prepare is
    /// `Reprepare` and rolls the whole transaction back, never a partial row.
    pub(crate) async fn apply_state(&self, tx: &Transaction<'_>) -> Result<(), ApplyError> {
        if !development::replace(tx, self.expected_revision(), &self.next, self.policies.identities.as_slice()).await? {
            return Err(ApplyError::Reprepare);
        }
        if let Some(from) = self.replace_from {
            development::replace_checkpoints(tx, self.system, from, &self.checkpoints, self.policies.identities.as_slice()).await?;
        }
        Ok(())
    }

    /// State plus the committed publication for the space actor.
    pub(crate) async fn apply(&self, tx: &Transaction<'_>, outbox: &mut Outbox) -> Result<(), ApplyError> {
        self.apply_state(tx).await?;
        outbox.sovereignty(crate::services::sovereignty::CommittedPublication {
            development: vec![DevelopmentPublication {
                system_id: self.system,
                row: Some(self.next.clone()),
                policies: self.policies.clone(),
            }],
            ..Default::default()
        });
        Ok(())
    }
}

/// Plan a refresh or delivery fold outside every lock: the initial zero row is
/// ensured first, then state/checkpoint/policy are read and, when the suffix
/// is affected, the canonical journal is replayed through EOF.
pub(crate) async fn plan(
    ex: &(impl Executor + ?Sized),
    sde: &crate::sde::Sde,
    retained: &crate::lua::RetainedPolicies,
    history: Arc<PolicyHistory>,
    system: i64,
    include_pending: Option<&str>,
    slices: &[SourceSlice],
    now: i64,
) -> Result<PreparedRefresh, CallError> {
    let first = history.segments.first().ok_or_else(|| invalid("empty development policy history"))?;

    development::ensure(ex, system, first.starts_at, first.ordinal, history.identities.as_slice()).await?;
    let row = development::read(ex, system).await?
        .filter(|row| row.system_id == system)
        .ok_or_else(|| invalid("development row missing after ensure"))?;
    // A segment published after the stored head but starting at or before the
    // stored anchor invalidates everything from its start onward.
    let earliest_new = history.segments.iter()
        .filter(|segment| segment.ordinal > row.activation_ordinal)
        .map(|segment| segment.starts_at)
        .min();
    let mut eligible: Vec<SourceSlice> = slices.iter()
        .filter(|slice| slice.order.occurred_at >= first.starts_at)
        .cloned().collect();
    eligible.sort_by(|a, b| a.order.cmp(&b.order));
    let min_slice = eligible.first().map(|slice| slice.order.occurred_at);
    let contaminated = earliest_new.is_some_and(|start| start <= row.evaluated_at);
    // Strict append only moves forward: a source before the stored decay
    // anchor needs the affected suffix rebuilt from a checkpoint.
    let late = eligible.first().is_some_and(|slice| slice.order.occurred_at < row.evaluated_at
        || row.tail.as_ref().is_some_and(|tail| slice.order <= *tail));
    let mut replace_from = None;
    let mut out = if contaminated || late {
        let segment = history.segment_at(now).ok_or_else(|| invalid("no active policy segment"))?;
        let interval = segment.definitions.decay_interval_ticks;
        if interval <= 0 { return Err(invalid("invalid decay interval")); }
        let trend_start = now.checked_sub(now.rem_euclid(interval)).ok_or_else(|| invalid("interval alignment"))?.max(segment.starts_at);
        let fold_from = min_slice.unwrap_or(i64::MAX).min(earliest_new.unwrap_or(i64::MAX)).min(trend_start);
        let checkpoint = development::checkpoint_before(ex, system, fold_from).await?
            .filter(|cp| history.segments.iter().all(|segment| segment.ordinal <= cp.activation_ordinal || segment.starts_at > cp.checkpoint_at));
        let (anchor, at, from) = match checkpoint {
            Some(cp) => (PointState { at: cp.checkpoint_at, military: cp.military_points, industrial: cp.industrial_points }, cp.checkpoint_at, cp.checkpoint_at.saturating_add(1)),
            None => (PointState { at: first.starts_at, military: 0.0, industrial: 0.0 }, first.starts_at, first.starts_at.max(1)),
        };
        let out = replay_all(ex, sde, &row, &history, anchor, include_pending, at.max(first.starts_at), now).await?;
        replace_from = Some(from);
        out
    } else {
        let mut fold = Fold::new(&row, PointState { at: row.evaluated_at, military: row.military_points, industrial: row.industrial_points }, row.tail.as_ref().map(|tail| tail.occurred_at), row.tail.clone(), &history, now)?;
        for slice in &eligible { fold.push(slice)?; }
        let out = fold.finish()?;
        if let Some(first_checkpoint) = out.checkpoints.first() {
            replace_from = Some(first_checkpoint.checkpoint_at);
        }
        out
    };
    out.next.revision = row.revision.checked_add(1).ok_or_else(|| invalid("revision overflow"))?;
    Ok(PreparedRefresh {
        system,
        previous: row,
        next: out.next,
        checkpoints: out.checkpoints,
        replace_from,
        head_ordinal: history.identities.last().map(|row| row.ordinal),
        retained: retained.clone(),
        policies: history,
    })
}

/// Refresh one system inside a short transaction and publish the committed row
/// to the space actor. `false` means the semantic state was already current.
pub(crate) async fn refresh_committed(db: &crate::db::Db, world: &crate::space::World, policies: &crate::lua::RetainedPolicies, history: &Arc<PolicyHistory>, mut observation: development::ObservationRow, now: i64) -> Result<bool, CallError> {
    let mut history = history.clone();
    for _ in 0..3 {
        if observation.development.is_none() && observation.system.as_ref().and_then(|row| row.claim_time).is_none() {
            return Ok(false);
        }
        let plan = Arc::new(plan(db, world.sde(), policies, history.clone(), observation.system_id, None, &[], now).await?);
        let previous = &plan.previous;
        let backdated = history.segments.iter().any(|segment|
            segment.ordinal > previous.activation_ordinal && segment.starts_at <= previous.evaluated_at);
        let strategic_changed = if backdated {
            false
        } else {
            let before = rules::project(Some(previous), observation.system.as_ref(), observation.capital.as_ref(), &history, observation.system_id, previous.evaluated_at)?;
            let after = rules::project(Some(previous), observation.system.as_ref(), observation.capital.as_ref(), &history, observation.system_id, now)?;
            before.strategic.level != after.strategic.level || before.defense_multiplier != after.defense_multiplier
        };
        let changed = plan.changed() || strategic_changed;
        let result = db.transaction(|tx, outbox: &mut Outbox| {
            let plan = plan.clone();
            Box::pin(async move {
                plan.prelock(tx).await?;
                if changed { plan.apply(tx, outbox).await?; }
                Ok(changed)
            })
        }, |changed, outbox| async move {
            crate::db::outbox::dispatch_world(changed, outbox, world).map_err(ApplyError::Call)
        }).await;
        match result {
            Ok(changed) => return Ok(changed),
            Err(ApplyError::Reprepare) => {
                history = super::activation::load(policies)?;
                observation = development::observations(db, &[observation.system_id]).await?.into_iter().next()
                    .ok_or_else(|| invalid("missing refresh observation"))?;
            }
            Err(error) => return Err(error.into_call()),
        }
    }
    Err(db_err(anyhow::anyhow!("development-index refresh stayed stale")))
}

